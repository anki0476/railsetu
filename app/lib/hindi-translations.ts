const translationCache = new Map<string, string>();

function translateHindiUncached(value: string): string {
  const exact = hindi[value];
  if (exact) return exact;

  for (const [pattern, render] of dynamicTranslations) {
    const match = value.match(pattern);
    if (match) return render(...match.slice(1));
  }

  if (value.includes(' · ')) {
    const parts = value.split(' · ');
    const localizedParts = parts.map((part) => translateHindi(part));
    if (localizedParts.some((part, index) => part !== parts[index])) return localizedParts.join(' · ');
  }

  let translated = stationNames[value] ?? value;
  for (const [english, hindiName] of Object.entries(stationNames)) {
    if (translated.includes(english)) translated = translated.replaceAll(english, hindiName);
  }
  for (const [english, hindiName] of Object.entries(trainNames)) {
    if (translated.includes(english)) translated = translated.replaceAll(english, hindiName);
  }
  return translated;
}

export function translateHindi(value: string): string {
  const cached = translationCache.get(value);
  if (cached !== undefined) return cached;
  const translated = translateHindiUncached(value);
  translationCache.set(value, translated);
  return translated;
}
